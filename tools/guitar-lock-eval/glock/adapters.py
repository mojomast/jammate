@dataclass
class AdapterResult:
    backend: str
    returncode: int
    stdout: str
    stderr: str
    out_dir: str
    binary: str
    binary_sha256: str
    backend_lib: str
    backend_lib_sha256: str

    def ok(self) -> bool:
        return self.returncode == 0


def _safe_fixture_name(rec_id: str) -> str:
    if not rec_id or any(c not in "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-_."
                         for c in rec_id):
        raise IntegrityError(f"recording id {rec_id!r} is not a safe fixture name")
    return rec_id


def build_rhythm_manifest(recordings: list[Recording], staging_dir: str) -> str:
    """Write a rhythm-eval manifest and symlink the audio into `staging_dir`.

    Returns the corpus directory (the manifest's parent). Private WAVs are only
    symlinked, never copied, and are never committed.
    """
    corpus_dir = os.path.join(staging_dir, "corpus")
    wav_dir = os.path.join(corpus_dir, "wav")
    os.makedirs(wav_dir, exist_ok=True)

    fixtures = []
    for rec in recordings:
        ann = rec.annotation
        if ann is None:
            raise IntegrityError(f"recording {rec.id} has no annotation; cannot run an adapter")
        name = _safe_fixture_name(rec.id)
        link = os.path.join(wav_dir, name + ".wav")
        if os.path.islink(link) or os.path.exists(link):
            os.remove(link)
        os.symlink(os.path.realpath(rec.audio_path_resolved), link)

        fx = {
            "name": name,
            "file": os.path.join("wav", name + ".wav"),
            "sha256": rec.declared["audio_sha256"],
            "license": rec.license or "unspecified",
            "provenance": rec.provenance or "",
            "notes": f"{rec.classification}; adapted by guitar-lock-eval",
            "tempoProfile": ann.tempo_profile,
            "durationSeconds": rec.declared["duration_seconds"],
            "sampleRate": rec.declared["sample_rate"],
            "meter": {
                "numerator": ann.meter_numerator,
                "denominator": ann.meter_denominator,
                "beatsPerBar": ann.beats_per_bar,
                "beatUnit": "quarter",
            },
            "beats": ann.beats,
            "onsets": ann.onsets,
            "trueSilenceSpans": ann.true_silence_spans,
            "silenceSpans": [],
            "silentBeats": [],
            "scenarioTags": (["core"] if rec.isCore() else ["guitar-lock-eval"]),
        }
        if ann.hasNominalBpm():
            fx["nominalBpm"] = ann.nominal_bpm
        if ann.bpm_start is not None:
            fx["bpmStart"] = ann.bpm_start
        if ann.bpm_end is not None:
            fx["bpmEnd"] = ann.bpm_end
        fixtures.append(fx)

    manifest = {
        "schemaVersion": 1,
        "corpus": {
            "id": "guitar-lock-eval-staging",
            "description": "Staging manifest generated by guitar-lock-eval; audio is symlinked, not committed.",
            "version": 1,
        },
        "conventions": {"beatToleranceSeconds": 0.07},
        "fixtures": fixtures,
    }
    import json
    manifest_path = os.path.join(corpus_dir, "manifest.json")
    with open(manifest_path, "w", encoding="utf-8") as fh:
        json.dump(manifest, fh, indent=2, allow_nan=False)
        fh.write("\n")
    return corpus_dir


def resolve_backend_lib(backend: str, explicit: str | None) -> str:
    if explicit:
        return explicit
    default = BACKEND_LIBS.get(backend)
    if not default:
        raise IntegrityError(f"unknown backend {backend!r}")
    # Prefer the EVAL-GUITAR-009 build root, then fall back to the existing
    # main-core plugin build if the caller placed it elsewhere.
    candidates = [default]
    for root in ("/home/mojo/projects/build-EVAL-005/main-core",):
        candidates.append(os.path.join(root, "librhythm-eval-" + backend + ".so"))
    for cand in candidates:
        if os.path.isfile(cand):
            return cand
    raise IntegrityError(
        f"backend library for {backend} not found (looked in {candidates}); "
        "build it or pass --" + backend + "-lib")


def run_tracker_diagnostics(binary: str, backend: str, backend_lib: str,
                            corpus_dir: str, out_dir: str, block_frames: int,
                            state_max_rows: int = 1000000) -> AdapterResult:
    if not os.path.isfile(binary) or not os.access(binary, os.X_OK):
        raise IntegrityError(f"tracker-diagnostics binary not executable: {binary}")
    if not os.path.isfile(backend_lib):
        raise IntegrityError(f"backend library not found: {backend_lib}")
    os.makedirs(out_dir, exist_ok=True)
    cmd = [
        binary, "--corpus", corpus_dir, "--out", out_dir,
        "--backend", backend, "--backend-lib", backend_lib,
        "--block", str(block_frames), "--trace-files", "all",
        "--state-max-rows", str(state_max_rows),
        "--label", "guitar-lock-eval-adapter",
    ]
    proc = subprocess.run(cmd, capture_output=True, text=True)
    return AdapterResult(
        backend=backend, returncode=proc.returncode, stdout=proc.stdout,
        stderr=proc.stderr, out_dir=out_dir, binary=binary,
        binary_sha256=sha256_file(binary), backend_lib=backend_lib,
        backend_lib_sha256=sha256_file(backend_lib))


def _read_state(path: str) -> list[dict]:
    rows = []
    with open(path, newline="", encoding="utf-8") as fh:
        for row in csv.DictReader(fh):
            rows.append({
                "block": int(row["blockIndex"]),
                "start": float(row["startSeconds"]),
                "end": float(row["endSeconds"]),
                "bpm": float(row["bpm"]),
                "phase_valid": row["phaseValid"] == "1",
            })
    return rows


def _read_beats(path: str) -> list[dict]:
    rows = []
    with open(path, newline="", encoding="utf-8") as fh:
        for row in csv.DictReader(fh):
            rows.append({
                "index": int(row["beatIndex"]),
                "block": int(row["blockIndex"]),
                "event": float(row["eventSeconds"]),
                "horizon": float(row["availabilitySeconds"]),
                "reported_sample": int(row["reportedSample"]),
            })
    return rows


def _nearest_bpm(state: list[dict], t: float) -> tuple[float | None, bool]:
    if not state:
        return None, False
    lo, hi = 0, len(state)
    while lo < hi:
        mid = (lo + hi) // 2
        if state[mid]["start"] < t:
            lo = mid + 1
        else:
            hi = mid
    if lo == 0:
        s = state[0]
    elif lo >= len(state):
        s = state[-1]
    else:
        a, b = state[lo - 1], state[lo]
        s = a if (t - a["start"]) <= (b["start"] - t) else b
    return s["bpm"], s["phase_valid"]


def reduce_trace(rec: Recording, backend: str, backend_kind: str,
                 out_dir: str, adapter: AdapterResult, block_frames: int,
                 compact_stride: int = 16) -> dict:
    """Reduce a tracker-diagnostics run into the bounded trace dict.

    All beats are kept. Tempo samples are compacted to preserve the trajectory
    shape (changes in bpm/phase_valid, nearest block to each beat, a fixed
    stride, and the endpoints) so the committed evidence stays bounded; the
    reduction rule is recorded in the trace metadata.
    """
    beats_path = os.path.join(out_dir, "beats", rec.id + ".csv")
    state_path = os.path.join(out_dir, "state", rec.id + ".csv")
    if not os.path.isfile(beats_path) or not os.path.isfile(state_path):
        raise IntegrityError(
            f"adapter output incomplete for {rec.id}: expected {beats_path} and {state_path}")
    state = _read_state(state_path)
    raw_beats = _read_beats(beats_path)

    beats = []
    for b in raw_beats:
        bpm, phase = _nearest_bpm(state, b["event"])
        beats.append({
            "event_seconds": b["event"],
            "horizon_seconds": b["horizon"],
            "reported_sample": b["reported_sample"],
            "reported_bpm": bpm,
            "bpm_phase_valid": phase,
        })

    keep = set()
    if state:
        keep.add(0)
        keep.add(len(state) - 1)
        prev_bpm = None
        prev_phase = None
        for i, s in enumerate(state):
            if prev_bpm is None or s["phase_valid"] != prev_phase or abs(s["bpm"] - prev_bpm) > 0.05:
                keep.add(i)
            if i % compact_stride == 0:
                keep.add(i)
            prev_bpm, prev_phase = s["bpm"], s["phase_valid"]
    # nearest block to every beat
    for b in raw_beats:
        best = None
        for i, s in enumerate(state):
            d = abs(s["start"] - b["event"])
            if best is None or d < best[0]:
                best = (d, i)
        if best is not None:
            keep.add(best[1])

    tempo_samples = []
    for i in sorted(keep):
        s = state[i]
        tempo_samples.append({
            "event_seconds": s["start"],
            "horizon_seconds": s["end"],
            "bpm": s["bpm"],
            "phase_valid": s["phase_valid"],
        })

    max_horizon = max((s["end"] for s in state), default=0.0)
    receipt = {
        "measured": True,
        "wall_utc": utc_now_iso(),
        "audio_seconds": max_horizon,
    }
    return {
        "schema": "guitar-lock-eval/trace/1.0",
        "recording_id": rec.id,
        "backend": backend,
        "backend_kind": backend_kind,
        "parent_backend": None,
        "derivation": None,
        "audio_sha256": rec.declared["audio_sha256"],
        "sample_rate": rec.declared["sample_rate"],
        "block_frames": block_frames,
        "source": {
            "tool": "tracker-diagnostics",
            "tool_sha256": adapter.binary_sha256,
            "backend_lib": adapter.backend_lib,
            "backend_lib_sha256": adapter.backend_lib_sha256,
            "generated_utc": utc_now_iso(),
        },
        "tempo_sampling": {
            "compacted": True,
            "stride_blocks": compact_stride,
            "note": "changes + nearest-to-beat + stride; all beats kept",
        },
        "receipt": receipt,
        "beats": beats,
        "tempo_samples": tempo_samples,
    }


def producer_sha256() -> str:
    """sha256 of the implementation that produces a derived candidate trace.

    Hashing the actual producer source means a placeholder cannot stand in for
    provenance and a changed algorithm changes the recorded hash.
    """
    return sha256_file(os.path.abspath(__file__))


def derive_beat_interval_trace(trace, rec: Recording, window: int = 4,
                               candidate_id: str = "diagnostic-beat-interval-bpm") -> dict:
    """Derive a causal beat-interval tempo candidate from another trace's beats.

    tempo at beat i = 60 / median(last <= `window` inter-beat intervals ending
    at i), published at beat i's event/horizon. This is available only once the
    interval is observed, so it stays causal. It is a derived diagnostic
    candidate computed inside this tool; it is never a production promotion.
    """
    events = [b.event_seconds for b in trace.beats]
    beats = []
    tempo = []
    recent: list[float] = []
    for i, b in enumerate(trace.beats):
        if i > 0:
            gap = events[i] - events[i - 1]
            if gap > 0:
                recent.append(gap)
                recent = recent[-window:]
        bpm = None
        if recent:
            gaps = sorted(recent)
            n = len(gaps)
            med = gaps[n // 2] if n % 2 else 0.5 * (gaps[n // 2 - 1] + gaps[n // 2])
            if med > 0:
                bpm = 60.0 / med
        beats.append({
            "event_seconds": b.event_seconds,
            "horizon_seconds": b.horizon_seconds,
            "reported_sample": b.reported_sample,
            "reported_bpm": bpm,
            "bpm_phase_valid": bpm is not None,
        })
        if bpm is not None:
            tempo.append({
                "event_seconds": b.event_seconds,
                "horizon_seconds": b.horizon_seconds,
                "bpm": bpm,
                "phase_valid": True,
            })
    return {
        "schema": "guitar-lock-eval/trace/1.0",
        "recording_id": rec.id,
        "backend": candidate_id,
        "backend_kind": "derived",
        "parent_backend": trace.backend,
        "derivation": ("causal beat-interval BPM: 60 / median(last<="
                       + str(window) + " inter-beat intervals); trace-level only"),
        "audio_sha256": rec.declared["audio_sha256"],
        "sample_rate": rec.declared["sample_rate"],
        "block_frames": trace.block_frames,
        "source": {
            "tool": "guitar-lock-eval derive-beat-interval",
            "tool_sha256": producer_sha256(),
            "generated_utc": utc_now_iso(),
        },
        "receipt": {
            "measured": True,
            "wall_utc": utc_now_iso(),
            "audio_seconds": trace.receipt.audio_seconds,
        },
        "beats": beats,
        "tempo_samples": tempo,
    }


def copy_raw_beats(out_dir: str, rec_id: str, dest_dir: str) -> tuple[str, str]:
    """Copy the raw beats CSV (small) into the evidence tree; return (dest, sha)."""
    src = os.path.join(out_dir, "beats", rec_id + ".csv")
    dest = os.path.join(dest_dir, rec_id + ".beats.csv")
    os.makedirs(dest_dir, exist_ok=True)
    shutil.copyfile(src, dest)
    return dest, sha256_file(dest)
