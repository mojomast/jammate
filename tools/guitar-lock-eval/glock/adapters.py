"""Replay adapters: reuse the existing tracker-diagnostics binary and reduce its
output to the trace model, plus a trace-level diagnostic candidate.

The adapter is the only place this tool executes another program. It:

  1. writes a rhythm-eval-compatible manifest for the recordings that need a
     trace (symlinking the audio, never copying private WAVs);
  2. invokes the pre-built `tracker-diagnostics` binary with the existing
     `librhythm-eval-{btrack,aubio}.so` plugins through the existing
     `jam_rhythm_create`/`jam_rhythm_destroy` convention;
  3. reduces the per-block beats/state CSVs to a bounded trace JSON that keeps
     the event/horizon clocks and an explicit receipt record.

The diagnostic candidate derives a tempo from the emitted beat intervals. It is
a trace-level, derived candidate computed entirely inside this new tool: it
changes no production source, selects no tracker and is labelled derived.
"""
